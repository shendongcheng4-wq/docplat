def main() -> int:
    bad = 0
    for name, src, want in CASES:
        got = book_layout(src)
        if got == want:
            print(f"✓ {name}")
        else:
            bad += 1
            print(f"✗ {name}\n   实际 {got!r}\n   期望 {want!r}")
    for name, args, want in MARK_CASES:
        got = page_mark(*args)
        if got == want:
            print(f"✓ {name}")
        else:
            bad += 1
            print(f"✗ {name}\n   实际 {got!r}\n   期望 {want!r}")
    total = len(CASES) + len(MARK_CASES)
    print(f"\n{'全部通过' if not bad else f'失败 {bad} 条'}"
          f"（{total - bad}/{total}）")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
