"""全局配置。所有阈值集中在这里，改一处即生效，且能写进日志便于回溯。

需要按环境改的三项走环境变量，其余都是实测调出来的常量：
  DOCPLAT_EXPORT_ROOT   导出交付目录（默认 桌面/书籍导出）
  DOCPLAT_GLM_BASE      GLM 服务地址（默认 http://127.0.0.1:8081）
  DOCPLAT_GLM_SERVE     GLM 启动脚本（默认 <项目>/scripts/glm_serve.py）
"""
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DB = DATA / "docplat.db"
PAGES = DATA / "pages"
EXPORTS = DATA / "exports"      # 库内暂存（--out 不指定时的旧行为），正式交付见 EXPORT_ROOT

# ---- 导出交付 ----
# 命名规则来自实际导入习惯：源目录是「丛书\卷\JPG」。
#   文件名 = JPG 的上一级（卷名）        → 某氏宗谱（卷一）.txt
#   外层目录 = JPG 的上上一级（丛书名）  → 书籍导出\某氏宗谱\
# 默认交付到桌面（作者的固定习惯），换机器时用 DOCPLAT_EXPORT_ROOT 覆盖。
EXPORT_ROOT = Path(os.environ.get("DOCPLAT_EXPORT_ROOT")
                   or Path.home() / "Desktop" / "书籍导出")
EXPORT_FORMAT = "txt"
# 导出时每页开头加一行页码（2026-11-04 用户定的全局规则，所有书一律生效）。
# 形态 `[p0129]`，单独一行、顶格、不与上下段接续；格式常量见 legacy.PAGE_MARK。
# 空白页/透印页不出页码 —— 页码跳号本身就说明那页没有字。
PAGE_MARKS = True
# 导出体检：0 字页要不要一律弹窗拦。
# 默认 False —— pipeline 已经判过「空白页（墨淡/透印/人工）」的页不再拦，
# 否则每本族谱/史料都有几十页真空白，用户每次导出都被弹一次（2026-11-05 抱怨）。
# 想看紧一点就置 True：任何 0 字未核对页都会拦住。
PREFLIGHT_WARN_BLANK = False
# 这些目录名只是「图片堆放层」，不代表书本身，起名字时要跳过
IMG_DIR_NAMES = {
    "jpg", "jpeg", "png", "bmp", "tif", "tiff", "webp", "gif", "pdf",
    "img", "image", "images", "imgs", "pic", "pics", "photo", "photos",
    "图片", "图像", "影像", "照片", "扫描", "扫描件", "原图", "书页",
}

# 「收集根」：源目录直接摊在它下面（书籍\书名\图片），说明没有丛书层。
# 这时外层目录用书名自己，别落成 书籍导出\书籍\书名.txt（2026-11-03 用户口径）。
SERIES_ROOT_NAMES = {"书籍", "书", "图书", "电子书", "books", "book"}

# 「批次目录」：用户常按日期分堆（书籍\1105\书名\图片），1105 是导入批次不是丛书名。
# 只由数字和分隔符组成、长度 ≥4 的目录名一律当批次目录处理 —— 外层还是用书名自己，
# 否则一本单卷书会落成 书籍导出\1105\书名.txt（2026-11-05 用户报六本书要导出时发现）。
# 真要有名叫「1105」的丛书，把 SERIES_ROOT_NAMES 里加回来即可。
BATCH_DIR_RE = re.compile(r"^[0-9][0-9\-_.]{3,}$")

# ---- 竖排族谱：表格按「列」读，不按「行」读 ----
# 古籍竖排从右往左，一页世系图 = 若干竖列，每列从上到下是一个人/一个世代。
# 但 VL 按 HTML <td> 的自然顺序输出（从左到右），摊平后变成「次子 平長子 次子 …」
# 这种横着拼的行 —— 列序反了，一列的话还会被下一列截断（2026-11-04 用户指出）。
# 这些书导出/展示时改成「先读最右列，从下往上逐格」，其余书仍按行。
VERTICAL_DOC_RE = re.compile(r"宗谱|宗譜|族谱|族譜|家谱|家譜")
# zu 是最早导入的那本《川前陳氏宗谱（卷一）》，id 是拼音缩写，名字里没有「宗谱」
VERTICAL_DOC_IDS = {"zu"}


def is_vertical(doc_id: str) -> bool:
    d = doc_id or ""
    return d in VERTICAL_DOC_IDS or bool(VERTICAL_DOC_RE.search(d))

# 分片：用内容 hash 前 2 位做目录，256 个分片，避免单目录几十万文件拖垮 NTFS
SHARD = 2

# ---- 模型服务 ----
# 默认指本机的 llama.cpp 服务（见 scripts/glm_serve.py）；换地址用环境变量。
GLM_BASE = os.environ.get("DOCPLAT_GLM_BASE") or "http://127.0.0.1:8081"
GLM_PROMPT = "Text Recognition:"
# 复杂表格（合并单元格 + 竖排表头）用默认提示词会让 GLM 读准表头和第一行之后
# 一路吐空单元格：先进性教育活动 p192 输出 4071 行、4058 个竖线、正文只有开头
# 那几行。换成一句中文的表格指令，同一张图 6.2 秒吐完整 HTML 表（含「小计 100」
# 行、rowspan/colspan 都在）。只在这类页被判退化时才用，正常页不受影响。
GLM_TABLE_PROMPT = ("请识别图片中的表格，逐行输出全部内容，保留合并单元格的对应关系，"
                    "不要省略任何一行，不要输出空单元格。")
# 目录页：行末的点线引导符会把 GLM 带进循环 —— 读到第一串「……」就停不下来，
# 一路吐到 token 上限（水西颂 p0014：32596 字里 3 万字是省略号，条目只开了个头）。
# 正解是抹点线（toc.strip_dot_leaders，2026-11-06 改成「定带 + 带内抹」之后，
# 同一页 32596 字 → 578 字 done 且字一个不错）。提示词只能在抹图失败时兜一手：
# 同一张原图换这句问，有时 3.4 秒出 721 字，但**不稳定**（同一提示词连跑 3 次，
# 1 次成功 2 次照样循环），所以它排在抹点线之后，当最后一招。
GLM_TOC_PROMPT = ("这是一页图书目录。请逐行识别目录条目，每条一行，保留「二、纪念文章」"
                  "这类小标题单独成行。条目名后面那串点线引导符直接跳过，"
                  "不要输出省略号，只保留条目文字和页码。")
GLM_MAX_TOKENS = 6000
GLM_MODEL = ""            # 空=自动从 /v1/models 探测

# ---- 超时与重试 ----
# v1 的教训：7.9% 的页超过 60s，最慢 1305s，把均值从 6s 拖到 35s。
# 硬超时 + 重试队列比"让模型慢慢想"划算得多。
PAGE_TIMEOUT = 120
MAX_RETRY = 2

# ---- 质量闸门 ----
COVER_OK = 0.90           # 内容齐全
COVER_PART = 0.75         # 可接受但需抽查
ORDER_OK = 0.80           # 有序相似度（仅标记列序差异）
SHORT_CHARS = 20          # 少于这个字数 → 大字/草书/题签版面

# ---- 表格页的字数下限 ----
# 表格/世系表页天然是多字页：39 页 vl 实测，正常页最少 49 字。
# 低于这个值基本是「图上密布文字、模型只吐出残片」——族谱里的世系树、
# 服制图（图内小字）就是这种失手方式，输出看着像表格其实是空壳。
TABLE_MIN_CHARS = 40

# ---- 空壳网格 ----
# VL 会把一页拆成海量单元格然后几乎全空（p0162：2730 格、5% 有字）。
# 只对真带 <td> 的输出生效，现代书的 markdown 表格不适用。
GRID_CELLS_MIN = 100      # 单元格数超过这个
GRID_FILL_MIN = 0.30      # 且填充率低于这个 → 判为拆格失败

# ---- 退化重复 ----
# 模型卡死后会把同一片段反复吐（p0147 `子二`×1967、p0188 `奏請`×2020）。
# 用 zlib 压缩冗余度衡量：正常页中位 0.28、P95 约 0.20~0.5，
# 退化页 0.97~0.99，中间没有样本。渲染时按同一阈值截断。
DEGEN_REDUNDANCY = 0.85

# ---- 退化重复（整块版）----
# 单片段重复由 DEGEN_REDUNDANCY 兜；但模型还会「整块重复」：溧阳商业志 p160
# 把同 8 行数值原样吐了 7 遍（丝网/钩卡/虾笼/拖虾网/围箔/黄鳝笼/塘网 全成了
# 一模一样的数），每行本身都不重复，zlib 冗余度只有 0.4，两道闸门全放过。
# 口径：k≥3 行的块、在同一页出现 ≥4 次、覆盖行数占比 ≥RATIO。
# 2410 页（7 本书）实测：只有 p160 命中 0.54，次高是族谱捐款名录 0.22
# （真的每笔都叫「懷德堂/伍佰元」，属正常），间隔够宽。
# 注意这是「判退化 → 记 review」，不是「压缩掉」——压缩会把整块真数据洗成
# 「（重复 N 次）」，静默丢内容比报错更糟。
BLOCK_REP_KMIN = 3
BLOCK_REP_TIMES = 4
BLOCK_REP_KMAX = 8
BLOCK_REP_RATIO = 0.30

# ---- 目录页点线（…………）----
# GLM 读到目录行末的点线会掉进循环：先进性教育活动 p9 读出第一行后就吐了
# 32744 个「…」，撞 6000 token 上限才停（16 秒、3.2 万字、冗余 1.00）。
# 这时候字其实看得清清楚楚，是点线把模型带沟里 —— 送图前把点抹掉即可。
#
# 口径（2026-11-06 改，水西颂 p0014 逼出来的）：
#   旧做法「等距链判定 → 整条水平带的候选一起抹」，对 1422px 的小字号扫描件两头不落好：
#   24 行只认出 10 条带（残点照样把模型带进循环，重读 32588 字），而整带抹又把
#   行首字的笔画碎块当点啃了（「陈毅」→「隖毅」）。
#   新做法分两段：先用**形态学闭运算**把小点连成一条细长的「线」定出点线带
#   （不依赖等距性，抗倾斜），再**只抹落在带内的小连通域** —— 字是大连通域，
#   本来就不在候选里，所以带判歪了也不会啃字。
#   同一页实测：32596 字死循环 → 578 字 done，24 条点线全部抹净，字一个不错。
TOC_DOT_MAX = 10          # 点状候选：宽或高超过这个就不算点（实测点 4~6px、字 15~30px）
TOC_DOT_WIDE = 16         # 宽度上限：相邻两点被 JPEG 糊成「短横」也不超过这个
TOC_DOT_AREA = 200        # 面积上限（单点 ≈21；两点粘连 ≈50；字的面积普遍 >200）
TOC_DOT_HMAX = 10         # 高度硬上限：正文汉字 15~30px，短横状的点线不会超过这个
TOC_MORPH_W = 25          # 闭运算横向核宽：点间距小于它就连成同一条带
TOC_BAND_MAX_H = 14       # 点线带的厚度上限，再厚就是成行小字了
TOC_SPAN_MIN = 120        # 点线带的最小横向跨度（「后 记………260」也才这么长）
TOC_SPAN_RATIO = 0.08     # 同时不小于图宽的 8%（大页按比例收）

# ---- vl 失败后回退 GLM 纯文本 ----
# 族谱的世系表/世系图/服制图，字本来就是按行按列排的短条目，不需要「表格」这层结构。
# vl 一旦判定失败（漏识 / 拆格崩），保留原样只剩空格子和碎格子，所以统一换成 GLM 的
# 纯文本清单 —— 代价是丢结构，而这些版面本来就没有值得保留的结构。
# 唯一门槛：换成纯文本后不能明显变少，否则等于白换。
FALLBACK_MIN_KEEP = 0.8        # 拆格崩页：结构是废的，0.8 倍即可
FALLBACK_MIN_KEEP_LEAK = 1.0   # 漏识页：结构也留着没用，但字数不能倒退

# 生产模式（无基准）的可疑信号
MIN_CHARS_PER_1K_PX = 0.02   # 每千像素墨迹面积对应的最少字数
BLOAT_RATIO = 3.0            # 输出字数 / 预期字数 超过这个值 → 疑似重复生成

# ---- 「这一页怎么这么慢」标记 ----
# 单页耗时的经验模型（2026-11-05 按 pages.sec 的 2500+ 页拟合）：
#   正常页 ≈ 1.6s 预填充（看图）+ 0.002s/字（GLM 出字）
# 只有「远超这个预期」才值得警惕：实测那四页各 67 秒、却只有 630~690 字，
# 是请求被晾在服务侧干等（GPU 停顿 / 服务重启），不是模型变慢。
# 只看绝对秒数会把「字多的长页」一起冤枉 —— 3000 字的页本来就该 8 秒。
SLOW_PAGE_SEC = 15.0         # 绝对下限：不到这个秒数一律不标
SLOW_FACTOR = 2.5            # 且要超过「按字数算的预期」这么多倍
SLOW_BASE_SEC = 1.6          # 预填充固定开销
SLOW_SEC_PER_CHAR = 0.002    # 每字出字开销

# ---- 版面真值清单 ----
# 按顺序加载，后面的覆盖前面的：routing_242 是 v1 基准自动生成的，
# layout_truth 是人工看图核对后的修正（v1 把世系行传误标成正文）。
TRUTH_FILES = ("routing_242.json", "layout_truth.json")

# ---- 结构闸门（核心）----
# 判断「这一页是分格条目（世系表/目录/服制图）而不是连续正文」。
# 必须在 GLM 跑完之后判：图像侧判不出来（三次尝试，精确率 17-28%）。
# 实测（2026-10-30，242 页，修正标签后）：命中 42/49 结构化页，误报 0。
STRUCT_MED_MAX = 8.0      # 行字中位数 <= 这个 → 短行
STRUCT_LINES_MIN = 10     # 且行数 >= 这个
STRUCT_SHORT_RATIO = 0.8  # 且「<=6 字的行」占比 >= 这个
STRUCT_PIPE_MIN = 2       # 或者有 >= 2 行带 "|" 的 markdown 表格（现代书常见）
ESCALATE_TO = "vl"        # 被结构闸门判为中招的页升级到哪个通道

# ---- 可选：预训练版面检测（PP-DocLayout，CPU）----
